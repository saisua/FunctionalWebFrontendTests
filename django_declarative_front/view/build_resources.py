from pathlib import Path
from itertools import chain, repeat
from textwrap import dedent
import inspect
import importlib
import ast
import re
from textwrap import dedent
from dataclasses import dataclass, field

from django.conf import settings

from django_declarative_front.page.page import Page
from django_declarative_front.static.state_machine.transition import Transition


_page_re = re.compile(r"(\W|^)((?:Meta\.)?_page.\w+(?:\.\w+)*)")


BASE_DIR = settings.BASE_DIR


@dataclass
class built_resources:
	page_script: Path | None = None
	stylesheets: list[Path] = field(default_factory=list)
	back_methods: Path | None = None
	front_view_class: Path | None = None
	transitions_out: list[Path] = field(default_factory=list)


def gen_build_resources(
	cls: type,
	view_static_path: Path,
	back_endpoints: list[str],
	back_attr_endpoints: list[str],
	front_functions: list[str],
) -> built_resources:
	reference = built_resources()

	if hasattr(cls, 'Meta'):
		meta_cls = cls.Meta
	else:
		meta_cls = None

	view_meta: list[str] = list()
	view_meta_class: list[str] = []

	page: Page | None = None
	_page_in_meta = False
	if hasattr(cls, "_page"):
		page = cls._page
	elif hasattr(meta_cls, "_page"):
		page = meta_cls._page
		_page_in_meta = True

	if page is not None:
		result = Page._builder_start.copy()
		for child in page.body.children:
			child.builder(output=result)

		script_path = view_static_path / "__script.py"
		script_path.write_text(
			'# Code autogenerated from a Python Page object\n\n' +
			'\n'.join(result)
		)
		reference.page_script = script_path

		if _page_in_meta:
			meta_src = view_meta_class
		else:
			meta_src = view_meta
		meta_src.append("_page = document")

		# Generate one_page transition diff scripts
		for name, member in inspect.getmembers(cls.__base__):
			if not isinstance(member, Transition):
				continue
			for from_state, (to_state, trans_type) in member.states.items():
				if not isinstance(to_state, str):
					continue
				if to_state.startswith('http://') or to_state.startswith('https://'):
					continue

				trans_type, modifiers = trans_type.rstrip('] ').split('[', 1)
				if '1' not in modifiers:
					continue

				to_state = Path(to_state)
				if not to_state.exists():
					if (BASE_DIR / to_state).exists():
						to_state = BASE_DIR / to_state
					# elif  # TODO: Relative to cls
					else:
						raise ValueError(f"Not found to_outside one_page transition file {to_state}")

				to_state_module_name = to_state.name
				module_path = str(to_state.relative_to(BASE_DIR.parent)).replace('/', '.')
				if module_path.endswith('.py'):
					module_path = module_path[:-3]
				module = importlib.import_module(module_path)

				for obj in vars(module).values():
					if not isinstance(obj, type):
						continue

					if cls.__base__.__base__ in obj.__bases__:
						transition_view = obj
						break
				else:
					raise ValueError(f"Not found BaseView class in to_outside one_page transition file {to_state}")

				transition_page: Page | None = None
				if hasattr(transition_view, "_page"):
					transition_page = transition_view._page
				elif hasattr(transition_view, 'Meta') and hasattr(meta_cls.Meta, "_page"):
					transition_page = transition_view.Meta._page

				if transition_page is not None:
					front_transition_path = view_static_path / f"to_{to_state_module_name}"
					front_transition_path.write_text('\n'.join(
						page.diff_builder(transition_page)
					))
					print(f"Generated page diff to {front_transition_path}")
				else:
					print(f"[Warning] transition to {to_state} has no _page")


	stylesheets = None
	_sheets_in_meta = False
	if hasattr(cls, "_stylesheets"):
		stylesheets = cls._stylesheets
	elif hasattr(meta_cls, "_stylesheets"):
		stylesheets = meta_cls._stylesheets
		_sheets_in_meta = True

	static_folder = view_static_path.parent
	if stylesheets is not None:
		if not isinstance(stylesheets, (list, tuple, set)):
			stylesheets = [stylesheets]

		stylesheets_base_path = Path(BASE_DIR, "generated").absolute()
		sheet_url_dict = dict()
		sheet_output_paths = None
		for stylesheet in stylesheets:
			if hasattr(stylesheet, '_output_paths'):
				sheet_output_paths = stylesheet._output_paths

				if not isinstance(sheet_output_paths, (list, tuple)):
					sheet_output_paths = [sheet_output_paths]

				sheet_output_paths = [
					static_folder / p
					for p in sheet_output_paths
				]
			else:
				sheet_output_paths = [
					view_static_path / f"{stylesheet.__name__}.css"
				]

			sheet_url_dict[stylesheet.__name__] = str(Path(
				"static",
				"generated_pages",
				sheet_output_paths[0].relative_to(stylesheets_base_path)
			))

			stylesheet_src = (
				'/* CSS autogenrated from a Python CSS object */\n' +
				stylesheet.generate()
			)
			for output_path in sheet_output_paths:
				output_path.write_text(
					stylesheet_src
				)

			reference.stylesheets.extend(sheet_output_paths)

		if sheet_output_paths:
			if _sheets_in_meta:
				meta_src = view_meta_class
			else:
				meta_src = view_meta
			meta_src.extend((
				"_stylesheets = {",
				"\tname: next((s for s in document.styleSheets if str(s.href) == url), None)",
				f"\tfor name, url in {sheet_url_dict!r}.items()",
				"}",
			))

	if hasattr(cls, "_endpoint"):
		view_endpoint = cls._endpoint
		view_meta.append(f"_endpoint = {str(view_endpoint)!r}")
	elif hasattr(meta_cls, "_endpoint"):
		view_endpoint = meta_cls._endpoint
		view_meta_class.append(f"_endpoint = {str(view_endpoint)!r}")
	else:
		raise ValueError("Missing _endpoint")

	if back_endpoints or back_attr_endpoints:
		back_endpoints_src: str = '\n'.join((
			f'def {endpoint_name}(*args, **kwargs): '
			'return asyncio.create_task('
			'make_request('
			f'"{view_endpoint}/{endpoint_name}",'
			'*args,'
			f'method={method!r},'
			'**kwargs'
			'))'
			for endpoint_name, method in chain(
				zip(back_endpoints, repeat('POST')),
				zip(back_attr_endpoints, repeat('GET'))
			)
		))

		back_methods_path = view_static_path / "back_access_endpoint_methods.py"
		back_methods_path.write_text(
			back_endpoints_src
		)
		reference.back_methods = back_methods_path

	front_view_meta_src: str = "\n\t" + "\n\t".join(view_meta)
	if view_meta_class:
		front_view_meta_src += "\n\tclass Meta:\n\t\t" + "\n\t\t".join(view_meta_class)

	front_class_name = "PageView"
	front_class_def = '\n'.join((
		"BaseView = StateMachine",
		'\n\t'.join([
			f'class {front_class_name}(StateMachine, Reactive):',
			'def __init__(self, *args, **kwargs):',
			'\tfor base in type(self).__bases__:',
			'\t\tbase.__init__(self, *args, **kwargs)'
		])
	))

	glob = globals()
	loc = locals()

	front_var_definitions: list[str] = list()
	source = inspect.getsource(cls.__base__)
	tree = ast.parse(source)
	for node in tree.body[0].body:
		attr_name = None
		segment = None

		if isinstance(node, ast.ClassDef):
			attr_name = node.name

			if attr_name == "Meta":
				continue

		elif isinstance(node, ast.AnnAssign):
			if isinstance(node.target, ast.Name):
				attr_name = node.target.id

		elif isinstance(node, ast.Assign):
			for target in node.targets:
				if isinstance(target, ast.Name):
					attr_name = target.id
					break

		elif (
			isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and 
			not inspect.isfunction(getattr(cls, node.name))
		):
			front_functions.append(ast.unparse(node))
			continue

		elif isinstance(node, ast.Expr) and hasattr(node, "value"):
			segment = ast.get_source_segment(source, node.value)

		else:
			continue

		if attr_name and not attr_name.startswith("_"):
			segment = ast.get_source_segment(source, node)

		if segment:
			try:
				segment = _page_re.sub(
					lambda m: m.group(1) + eval(f"cls.{m.group(2)}", glob, loc),
					segment
				)
			except TypeError:
				raise NameError("Wrong usage of _page")

			front_var_definitions.append(segment)

	# for attr in StateMachine.__annotations__.keys():
	# 	pass

	if front_var_definitions:
		front_var_definitions_src = '\n\t' + '\n\t'.join(front_var_definitions)
	else:
		front_var_definitions_src = ''

	if back_endpoints or back_attr_endpoints:
		front_back_functions_src = '\n\t' + '\n\t'.join([
			f'_{endpoint_name} = {endpoint_name}'
			for endpoint_name in chain(
				back_endpoints,
				back_attr_endpoints,
			)
		])
	else:
		front_back_functions_src = ''

	if front_functions:
		front_functions_src: str = '\n\t' + '\n\t'.join([
			*(
				fn_line
				for fn_line in chain(*(
					dedent(
						front_fn
						if isinstance(front_fn, str)
						else
						inspect.getsource(
							front_fn
						).replace(cls.__base__.__name__, front_class_name)
					).split('\n')
					for front_fn in (
						getattr(cls, front_fn_name, front_fn_name)
						for front_fn_name in front_functions
					)
					if (
						front_fn is not None
						and (
							inspect.isfunction(front_fn)
							or inspect.ismethod(front_fn)
							or inspect.isclass(front_fn)
							or inspect.isbuiltin(front_fn)
							or isinstance(front_fn, str)
						)
					)
				))
				if fn_line.strip()
			)
		])
	else:
		front_functions_src = ''

	if (
		front_view_meta_src or
		front_functions_src or
		front_back_functions_src or
		front_var_definitions_src
	):
		front_startup_code = getattr(cls, '_front_startup', '')
		if front_startup_code:
			front_startup_code = '\n' + dedent(front_startup_code)

		front_view_path = view_static_path / "front_view_class.py"
		front_view_path.write_text(
			front_class_def +
			front_view_meta_src +
			front_var_definitions_src +
			front_back_functions_src +
			front_functions_src +
			'\nview = PageView()\nprint("view initialized")' +
			front_startup_code
		)
		reference.front_view_class = front_view_path

	return reference
